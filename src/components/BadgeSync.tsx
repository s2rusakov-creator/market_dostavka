"use client";

import { useEffect } from "react";
import { setBadge } from "@/lib/nativeBridge";

/**
 * Держит значок на иконке приложения в согласии с непрочитанным.
 *
 * Ставится на страницу списка чатов — единственное место, где число
 * непрочитанных и так посчитано. Отдельный запрос ради значка на каждой
 * странице не нужен: пуш приносит свежее число с собой, а здесь мы поправляем
 * его, когда человек переписки прочитал.
 *
 * В браузере не делает ничего.
 */
export function BadgeSync({ count }: { count: number }) {
  useEffect(() => {
    void setBadge(count);
  }, [count]);

  return null;
}
