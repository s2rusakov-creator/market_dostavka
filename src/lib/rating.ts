/**
 * Рейтинг участника.
 *
 * Голая средняя при малом числе оценок врёт грубо: одна пятёрка давала ★5,0 и
 * ставила новичка выше человека с сорока сделками и ★4,8, а одна
 * несправедливая единица давала ★1,0 и фактически выгоняла с площадки.
 *
 * Лечится не весами за отдельные оценки, а двумя правилами.
 *
 * Первое: пока оценок мало, числа нет вообще — «новый участник» честнее любой
 * цифры, посчитанной по одному отзыву.
 *
 * Второе: дальше средняя подмешивается к средней по площадке тем сильнее, чем
 * меньше у человека отзывов. Это обычное сжатие к среднему, то же, что в
 * рейтинге IMDB: одна пятёрка перестаёт быть козырем, одна единица —
 * приговором, а десять честных сделок весят столько же, сколько раньше весил
 * случайный первый отзыв.
 *
 * Весов «пятёрка легче единицы», как в такси, здесь нет намеренно: там за
 * рейтингом стоит порог отключения, а YOL никого не отключает — аккаунт
 * заводится четырьмя способами без подтверждения. Коэффициент, за которым
 * ничего не стоит, — просто ещё одно число на карточке.
 */

/** Сколько оценок нужно, чтобы вообще показать число. */
export const MIN_REVIEWS_TO_SHOW = 3;

/**
 * Вес прикидки. Грубо: «столько оценок средним по площадке» подмешивается
 * к собственным. Три — компромисс: новичок не выглядит ни звездой, ни
 * изгоем, а к десятку отзывов влияние прикидки почти исчезает.
 */
export const PRIOR_WEIGHT = 3;

/**
 * Средняя по площадке, когда её ещё не из чего считать: на пустой площадке
 * отзывов нет вовсе. Значение нейтральное — не хвалит и не топит.
 */
export const FALLBACK_MEAN = 4.5;

/**
 * Оценка со сжатием к средней по площадке.
 * null — оценок слишком мало, показывать нечего.
 */
export function shrunkRating(
  sum: number,
  count: number,
  platformMean: number = FALLBACK_MEAN
): number | null {
  if (count < MIN_REVIEWS_TO_SHOW) return null;

  const mean = Number.isFinite(platformMean) ? platformMean : FALLBACK_MEAN;
  return (sum + PRIOR_WEIGHT * mean) / (count + PRIOR_WEIGHT);
}

/** То же, но готовой строкой: одна цифра после запятой, как принято. */
export function formatRating(
  sum: number,
  count: number,
  platformMean?: number
): string | null {
  const value = shrunkRating(sum, count, platformMean);
  if (value === null) return null;
  return value.toFixed(1).replace(".", ",");
}

/**
 * Средняя по площадке из суммарных счётчиков.
 * Отзывов ещё нет — возвращаем нейтральную прикидку.
 */
export function platformMeanFrom(
  totalSum: number,
  totalCount: number
): number {
  if (totalCount <= 0) return FALLBACK_MEAN;
  return totalSum / totalCount;
}
