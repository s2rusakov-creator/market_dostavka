/**
 * Куда вернуть человека после входа.
 *
 * Раньше все четыре способа входа вели на главную. Нажал «предложить
 * доставку», ушёл логиниться, вернулся — и ищи заявку в ленте заново.
 * Теперь страницы, требующие входа, передают исходный адрес в `?next=`.
 *
 * Значение приходит из адресной строки, то есть от кого угодно, — поэтому
 * пропускаем только путь внутри своего сайта. Без этой проверки ссылка вида
 * `/login?next=https://чужой-сайт` увела бы человека наружу сразу после
 * ввода пароля, и выглядело бы это как действие самого YOL.
 */
export function safeNextPath(value: string | null | undefined): string | null {
  if (!value) return null;

  // Разрешён только абсолютный путь внутри сайта. Отсекаем и полные адреса
  // (`https://…`), и протокол-относительные (`//чужой-сайт`), и попытки
  // подсунуть их через обратный слэш, который часть браузеров нормализует.
  if (!value.startsWith("/")) return null;
  if (value.startsWith("//") || value.startsWith("/\\")) return null;

  // Возвращать на страницу входа бессмысленно — получилось бы кольцо.
  const путь = value.split("?")[0].split("#")[0];
  if (путь === "/login" || путь.endsWith("/login")) return null;

  return value;
}
