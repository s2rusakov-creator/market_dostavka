/**
 * Как часто чат спрашивает сервер о новых сообщениях.
 *
 * Вебсокеты для двух-трёх реплик избыточны, но и опрашивать всегда одинаково
 * часто неправильно: чат чаще открыт, чем используется — договорились и
 * оставили вкладку. Раньше он всё это время ходил на сервер каждые пять
 * секунд, а в мобильном приложении это ещё и батарея.
 *
 * Поэтому шаг зависит от того, сколько длится тишина. Любое движение —
 * своё сообщение, чужое сообщение, возврат во вкладку — считается активностью
 * и возвращает частый шаг.
 *
 * Политика вынесена из компонента, чтобы её можно было проверить тестом,
 * а не секундомером в браузере.
 */

/** Пока идёт разговор: ощущение живой переписки. */
export const POLL_ACTIVE_MS = 5_000;
/** После минуты тишины. */
export const POLL_IDLE_MS = 15_000;
/** После пяти минут тишины. */
export const POLL_QUIET_MS = 30_000;

export const IDLE_AFTER_MS = 60_000;
export const QUIET_AFTER_MS = 5 * 60_000;

/** Сколько ждать до следующего запроса при такой длительности тишины. */
export function nextPollDelay(quietForMs: number): number {
  if (quietForMs >= QUIET_AFTER_MS) return POLL_QUIET_MS;
  if (quietForMs >= IDLE_AFTER_MS) return POLL_IDLE_MS;
  return POLL_ACTIVE_MS;
}
